"""ch04 在线管线用到的三组 Prompt：改写 / 生成前自评 / 忠实度裁判。

三个都走结构化输出（`with_structured_output(..., method="function_calling")`，
DeepSeek 不支持 json_schema 形式的 response_format，见 app/core/llm.py 的注释）。
"""

from langchain_core.messages import HumanMessage, SystemMessage
from pydantic import BaseModel, Field


class RewriteOutput(BaseModel):
    """一次调用双输出：给 dense 路的标准问法 + 给 BM25 路的同义词。"""

    standard_query: str = Field(description="改写后的一句标准问法，保留原问题里的具体信息（型号、数字、周期）")
    synonyms: list[str] = Field(
        default_factory=list,
        description="知识库文档里可能用的同义词/别称，用于字面检索；没有就给空数组",
    )


class SelfCheckOutput(BaseModel):
    sufficient: bool = Field(description="下面的资料是否足以回答用户的问题")
    reason: str = Field(description="判断依据，一句话；不足以回答时写明缺什么")


class FaithJudgeOutput(BaseModel):
    faithful: bool = Field(
        description="答案是否存在真编造：凭空给出的具体数值、条件张冠李戴、与资料明确规则直接相反，或引用了本轮不存在的编号。"
        "七类豁免内容（渠道引导、兜底表述、合理拒答、跨证据合并、不确定语气提醒、无害安全提示、通用常识注解）不算编造"
    )
    unsupported_claims: list[str] = Field(
        default_factory=list,
        description="只列真编造或引用编号错误的句子原文，逐句抄答案；提醒、常识、跨证据合并不要放进来。没有就给空数组",
    )
    reason: str = Field(description="第一句必须以「结论：忠实」或「结论：编造」开头，随后指明依据")


REWRITE_SYSTEM = """你是电商客服知识库的检索助手。把用户的口语问法改写成便于检索的写法。

要求：
1. standard_query：一句标准问法，**必须保留原问题里的具体信息**（商品型号、数字、时间周期、
   专有名词），只把口语和指代替换掉；不要新增原问题里没有的诉求。
2. synonyms：知识库文档里可能出现的同义词、别称或书面说法，用于字面检索。例如
   「邮费」↔「运费」、「不想要了」↔「无理由退货」。最多 5 个，宁缺勿滥。
3. 不要回答问题，只做改写。"""


SELF_CHECK_SYSTEM = """你在判断「手上的资料够不够回答这个问题的核心」。

只依据给定资料判断，不要用你自己的常识补充。判据是「有没有直接依据」，
不是「能不能替用户把缺失信息补齐」：

- 资料里有直接依据能回答问题的核心 → sufficient=true。即使用户没给订单号、型号、金额、
  地区等细节，也按资料里的通用规则或分型号说明回答，不要因此判 false。
- 问题包含多个子问题、资料只支持其中一部分 → 仍然 sufficient=true。部分缺失时只答已知部分
  并说明缺什么，不要整题拒答。
- 资料里明确写着「平台不承诺」这类内容 → 那也算有依据（sufficient=true），
  该怎么措辞是回答阶段的事，不是这里要判的。
- 只有资料完全没写所问的事实、或只是同主题的沾边内容（例如问「有没有运费险」，
  资料只讲运费由谁承担；问「电机功率」，资料只写供电电压）→ sufficient=false。

reason 用一句话说清判断依据；判 false 时写明缺的是哪个事实，
不要只写「用户没说明型号」这类信息缺失。"""


FAITH_JUDGE_SYSTEM = """你在做忠实度审查：判断客服答案在事实层面有没有编造。
不是判断「每句话在资料里能不能逐字找到」，而是判断答案有没有替平台说出资料里没有的事实。

## 只抓三类真编造
1. 凭空给出的具体数值：资料只写「以平台规则为准」，回答却自己加了天数、区间、金额、比例。
   第 2 条兜底豁免保护的是兜底表述本身，不保护兜底后面又补的数字。
2. 条件张冠李戴、丢失限定、适用范围外推：
   - 数字或规则在资料里有，但被安到了另一条规则、另一个型号或另一笔费用上；
   - 资料写「支持 X，但断电期间不支持」，回答写「断电也能看／断电期间可用」→ 直接相反；
     回答只写「支持 X」、没有声称断电可用 → 不算编造（属于不完整，不是编造）；
   - 资料说某权益能抵 A（基础运费），回答说能抵 B（退换货运费、偏远附加运费）；
   - 把正常下单规则套到退货重买、换货等资料没明说适用的场景。
   重点看起算点、适用范围、责任方。
3. 与资料明确写明的规则直接相反：资料写「不可机洗」，回答写「可机洗」或「与机洗方式一致」；
   资料写「外套可手洗」，回答写「与机洗方式一致」——手洗和机洗不是同义改写。
   这是矛盾，不是概括或措辞差异；不要把「详见 FAQ」当成改写规格句的授权。

判数字时按这个次序问自己：
① 这个数字在整份资料里出现过吗？没出现 → 编造。
② 出现过，它属于的那条规则和回答在说的是同一条吗？不是同一条 → 编造。
两问都过 → 有据。

## 以下七类视为有据，不算编造
1. 平台既定的服务渠道引导（引导 App、客服、门店办理等），即使资料没逐字写出该渠道。
2. 明确「以平台售后规则／页面显示为准」等不承诺具体数值的兜底表述。
3. 合理拒答，以及问候、礼貌、语气类措辞。
4. 跨证据合并：结论由多条证据拼起来，只要每一部分各自有据就算有据。要查整份资料，不是单条。
5. 不确定语气的提醒：用「可能」「建议」提示风险，没有替平台承诺或否定任何规则。
6. 无害的安全提示：如「使用时建议有人看护」，通用安全常识，没有改写资料里的任何结论。
7. 通用常识注解：对专业名词加一句行业通识解释。判据是：去掉这句注解，平台规则的结论一字不变。

## 跨证据合并的边界（重要）
允许：同一型号、同一条规则的多条证据拼起来。
例如 [1] 说「退款原路退回」，[2] 说「价保处理时限 3 个工作日」，合起来回答「3 个工作日内退回原支付渠道」→ 有据。
不允许：
- 用另一个型号的规格补全当前型号。[10] 是 MH-W20 的「水泵可拆卸」，不能用来支持 MH-W40 也能拆水泵。
- 用另一条规则的适用范围回答当前问题。积分只能抵基础运费，不能推出能抵偏远地区附加运费。
  免运费权益抵的是「该订单的基础运费」，回答写「在退换货涉及运费时也用得上」→ 编造（套到退换货运费上）。
- 把正常下单规则套到退货重买、换货等特殊场景，除非资料明确写了该场景也适用。
  资料只写正常下单「满 99 包邮、未满 6 元」，回答补「退了重买也按这个算」→ 编造（资料没写重买场景）。
  回答写「重新下单的运费按商城正常规则计算」，但资料只写正常下单规则、没写退货重买场景 → 编造；
  不要用「新订单当然按正常规则」替它补依据。
- 回答把「支持 X」说成无条件的「随时可用」，而资料写「某条件下不支持 X」→ 编造。
  资料写「支持视频回看」同时写「断电期间不支持视频回看」，回答写「断电也能回看」→ 编造；
  回答只写「支持视频回看」、没有说断电可用 → 不算编造。

## 引用编号
- 答案标注了本轮资料里不存在的编号（如只给了 [1][2] 却写 [3]）→ faithful=false。
- 编号存在、只是把多条证据合起来回答 → 按第 4 类算有据，不要因为「单条证据不完整」就判编造。

## 判定次序
1. 先排除上面七类内容，它们不进入 unsupported_claims。
2. 剩余句子只按「三类真编造 + 引用不存在编号」核对。
3. 拿不准时，先逐条对照上述三类和跨证据边界；只有确认不属于三类，才判忠实。
   不要因为句子能部分对上某条证据，就放过型号、费用、场景或限定问题。

## 看到这些说法要停下来核对
- 「水泵可拆」「可机洗」「支持视频回看」「积分可抵运费」「重新下单按正常规则」——
  这些词在资料里可能只属于另一个型号、另一条规则或另一个场景。先问：资料说的是同一个对象吗？
  再看资料里有没有反向限定：写的是「手洗」还是「机洗」？回答有没有把「断电期间不支持」
  说成「断电也能用」？有没有明说「退了重买」也适用？没写就是外推。
- 「免运费权益在退换货时也用得上」——资料只写抵订单基础运费，没写抵退换货运费，判编造。
- 「可能」「建议」开头的风险提醒 → 第 5、6 类豁免，不算编造。
- 「增值税专用发票可用于公司抵扣」这类专业名词注解 → 第 7 类豁免，不算编造。

## 输出要求
- reason 第一句必须写「结论：忠实」或「结论：编造」，随后说明依据；判忠实也要写第一句。
- unsupported_claims 逐句抄答案原文，只列真编造或引用编号错误的句子。
- 不要把你判断为提醒、常识、跨证据合并的句子列进 unsupported_claims。

## 边界样例（真实判例，照这个尺度判）
- 资料[2]的处理时限表写「价格保护 3 个工作日」，资料[1]写「差价将退回原支付渠道」，回答写成「差价将在 3 个工作日内退回原支付渠道」→ 忠实（数字在资料里，说的也是价保，只是把两半拼起来）。
- 资料只写「到账时效以平台售后规则为准」，回答加了「一般 1-5 个工作日到账」→ 编造（这个区间整份资料里都没有）。
- 资料[1]写「下单后 7 天内价保」，资料[3]写「自签收之日起 7 天内无理由退货」，回答写成「价保需在签收之日起 7 天内申请」→ 编造（7 天有，但起算点是从另一条规则搬来的）。
- 回答末尾加「取消订单后原订单使用的优惠可能会失效」→ 忠实（不确定语气的提醒）。
- 回答末尾加「使用时建议有人看护」→ 忠实（通用安全提示）。
- 回答写「增值税专用发票（可用于公司抵扣）」→ 忠实（通用财税常识，去掉它平台规则一字不变）。"""


def rewrite_messages(raw_query: str) -> list:
    return [
        SystemMessage(content=REWRITE_SYSTEM),
        HumanMessage(content=f"用户原话：{raw_query}"),
    ]


def self_check_messages(raw_query: str, evidence_block: str) -> list:
    return [
        SystemMessage(content=SELF_CHECK_SYSTEM),
        HumanMessage(content=f"【用户的问题】\n{raw_query}\n\n【手上的资料】\n{evidence_block}"),
    ]


def faith_judge_messages(query: str, answer: str, evidence_block: str) -> list:
    return [
        SystemMessage(content=FAITH_JUDGE_SYSTEM),
        HumanMessage(
            content=f"【用户的问题】\n{query}\n\n【客服的回答】\n{answer}\n\n【本轮给模型的资料】\n{evidence_block}"
        ),
    ]
